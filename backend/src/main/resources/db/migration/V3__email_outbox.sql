CREATE TABLE email_outbox (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  event_key VARCHAR(200) NOT NULL,
  recipient VARCHAR(255) NOT NULL,
  subject VARCHAR(160) NOT NULL,
  body VARCHAR(5000) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
  attempts INTEGER NOT NULL DEFAULT 0,
  available_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  last_error VARCHAR(500),
  delivered_at TIMESTAMP(6),
  created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT pk_email_outbox PRIMARY KEY (id),
  CONSTRAINT uq_email_outbox_event_key UNIQUE (event_key),
  CONSTRAINT chk_email_outbox_status CHECK (status IN ('PENDING', 'PROCESSING', 'RETRY', 'DELIVERED', 'FAILED'))
);

CREATE INDEX idx_email_outbox_due ON email_outbox (status, available_at, id);
