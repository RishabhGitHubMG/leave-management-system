CREATE TABLE email_delivery_attempts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  outbox_id BIGINT NOT NULL,
  attempt_number INTEGER NOT NULL,
  outcome VARCHAR(20) NOT NULL,
  error_type VARCHAR(100),
  created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT pk_email_delivery_attempts PRIMARY KEY (id),
  CONSTRAINT fk_email_delivery_attempts_outbox FOREIGN KEY (outbox_id) REFERENCES email_outbox (id)
);

CREATE INDEX idx_email_delivery_attempts_outbox ON email_delivery_attempts (outbox_id, created_at);
